import type { EnvVariableEntry, EnvFileRecord, EnvCompareResult } from '../../types/config';

const SENSITIVE_KEY_REGEX = /(password|secret|token|api_?key|auth|private_?key|cert|credential|bearer|database_?url|db_?url|db_?pass)/i;

/**
 * Parses raw .env file text into structured variable entries.
 */
export function parseEnvFile(content: string): EnvVariableEntry[] {
  if (!content) return [];

  const lines = content.split('\n');
  const entries: EnvVariableEntry[] = [];
  let pendingComment: string | undefined = undefined;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();

    if (!line) {
      pendingComment = undefined;
      continue;
    }

    if (line.startsWith('#')) {
      // Collect comment
      pendingComment = line.replace(/^#+\s*/, '');
      continue;
    }

    const eqIndex = line.indexOf('=');
    if (eqIndex === -1) {
      continue;
    }

    const key = line.slice(0, eqIndex).trim();
    let value = line.slice(eqIndex + 1).trim();

    // Strip wrapping quotes
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    const isSecret = SENSITIVE_KEY_REGEX.test(key);

    entries.push({
      id: `env-var-${i}-${key}`,
      key,
      value,
      comment: pendingComment,
      isSecret,
      isActive: true,
    });

    pendingComment = undefined;
  }

  return entries;
}

/**
 * Stringifies variable entries back into .env format.
 */
export function stringifyEnvFile(entries: EnvVariableEntry[]): string {
  const lines: string[] = [];

  for (const entry of entries) {
    if (entry.comment) {
      lines.push(`# ${entry.comment}`);
    }
    if (!entry.isActive) {
      lines.push(`# ${entry.key}=${entry.value}`);
    } else {
      // Quote if contains spaces or special characters
      const needsQuotes = entry.value.includes(' ') || entry.value.includes('\n');
      const valStr = needsQuotes ? `"${entry.value}"` : entry.value;
      lines.push(`${entry.key}=${valStr}`);
    }
  }

  return lines.join('\n');
}

/**
 * Generates a clean .env.example template from .env content without copying any secret values.
 */
export function generateEnvExample(envContent: string): string {
  const entries = parseEnvFile(envContent);
  const lines: string[] = [
    '# Generated by DevDesk .env.example Helper',
    '# All secret credentials and values have been sanitized',
    '',
  ];

  for (const entry of entries) {
    if (entry.comment) {
      lines.push(`# ${entry.comment}`);
    }

    if (entry.isSecret) {
      lines.push(`${entry.key}=`);
    } else {
      // Keep non-sensitive defaults like PORT=3000 or NODE_ENV=development
      const isPublicDefault = /^(port|node_env|debug|app_env|timezone|locale)$/i.test(entry.key);
      lines.push(`${entry.key}=${isPublicDefault ? entry.value : ''}`);
    }
  }

  return lines.join('\n');
}

/**
 * Compares two .env file contents key-by-key without revealing sensitive secret values.
 */
export function compareEnvFiles(contentA: string, contentB: string): EnvCompareResult[] {
  const entriesA = parseEnvFile(contentA);
  const entriesB = parseEnvFile(contentB);

  const mapA = new Map(entriesA.map((e) => [e.key, e]));
  const mapB = new Map(entriesB.map((e) => [e.key, e]));

  const allKeys = Array.from(new Set([...mapA.keys(), ...mapB.keys()])).sort();

  return allKeys.map((key) => {
    const varA = mapA.get(key);
    const varB = mapB.get(key);
    const isSecret = Boolean(varA?.isSecret || varB?.isSecret || SENSITIVE_KEY_REGEX.test(key));

    if (varA && !varB) {
      return {
        key,
        status: 'missing_in_b',
        valA: isSecret ? '••••••••' : varA.value,
        valB: undefined,
        isSecret,
      };
    }

    if (!varA && varB) {
      return {
        key,
        status: 'missing_in_a',
        valA: undefined,
        valB: isSecret ? '••••••••' : varB.value,
        isSecret,
      };
    }

    if (varA && varB) {
      const isSame = varA.value === varB.value;
      return {
        key,
        status: isSame ? 'same' : 'different',
        valA: isSecret ? '••••••••' : varA.value,
        valB: isSecret ? '••••••••' : varB.value,
        isSecret,
      };
    }

    return {
      key,
      status: 'same',
      isSecret,
    };
  });
}

